package main

import (
	"fmt"
	"go/format"
	"sort"
	"strconv"
	"strings"
)

// goMethod maps a PHP method name to its Go name and doc line.
var goMethod = map[string]struct{ name, doc string }{
	"label":       {"Label", "human label"},
	"description": {"Description", "longer description"},
	"icon":        {"Icon", "icon key the clients map to an asset"},
}

func render(e *phpEnum) ([]byte, error) {
	var b strings.Builder
	typ := e.Name
	casesVar := strings.ToLower(typ[:1]) + typ[1:] + "Cases"
	constName := func(c phpCase) string { return typ + pascal(c.Name) }

	fmt.Fprintf(&b, "// Code generated by enumgen from %s. DO NOT EDIT.\n\n", e.Source)
	b.WriteString("package enums\n\nimport \"slices\"\n\n")

	fmt.Fprintf(&b, "// %s mirrors the PHP enum %s (%s).\n", typ, typ, e.Source)
	fmt.Fprintf(&b, "type %s string\n\n", typ)

	fmt.Fprintf(&b, "// %s cases, in PHP case order.\nconst (\n", typ)
	for _, c := range e.Cases {
		fmt.Fprintf(&b, "\t%s %s = %s // PHP %s\n", constName(c), typ, strconv.Quote(c.Value), c.Name)
	}
	b.WriteString(")\n\n")

	fmt.Fprintf(&b, "var %s = []%s{\n", casesVar, typ)
	for _, c := range e.Cases {
		fmt.Fprintf(&b, "\t%s,\n", constName(c))
	}
	b.WriteString("}\n\n")

	fmt.Fprintf(&b, "// %sCases returns every case in PHP case order (PHP %s::cases()).\n", typ, typ)
	fmt.Fprintf(&b, "func %sCases() []%s { return slices.Clone(%s) }\n\n", typ, typ, casesVar)

	fmt.Fprintf(&b, "// %sValues returns the backed values in PHP case order (PHP %s::values()).\n", typ, typ)
	fmt.Fprintf(&b, "func %sValues() []string { return valuesOf(%s) }\n\n", typ, casesVar)

	b.WriteString("// IsValid reports whether e is one of the declared cases.\n")
	fmt.Fprintf(&b, "func (e %s) IsValid() bool {\n\tswitch e {\n\tcase ", typ)
	for i, c := range e.Cases {
		if i > 0 {
			b.WriteString(", ")
		}
		b.WriteString(constName(c))
	}
	b.WriteString(":\n\t\treturn true\n\t}\n\treturn false\n}\n\n")

	fmt.Fprintf(&b, "// %sFrom returns the case backed by v and whether it exists (PHP %s::tryFrom).\n", typ, typ)
	fmt.Fprintf(&b, "func %sFrom(v string) (%s, bool) {\n\te := %s(v)\n\treturn e, e.IsValid()\n}\n\n", typ, typ, typ)

	for _, t := range e.Methods {
		gm := goMethod[t.Method]
		param := ""
		if t.Method != "icon" {
			param = "locale string"
		}
		switch {
		case t.Kind == kindIsValue:
			fmt.Fprintf(&b, "// %s returns the %s: the backed value itself (PHP %s()).\n", gm.name, gm.doc, t.Method)
			param = strings.Replace(param, "locale", "_", 1)
		case t.Kind == kindSingle && param != "":
			fmt.Fprintf(&b, "// %s returns the %s. The PHP %s() has one table for every locale, so locale is ignored.\n",
				gm.name, gm.doc, t.Method)
			param = strings.Replace(param, "locale", "_", 1)
		case t.Kind == kindSingle:
			fmt.Fprintf(&b, "// %s returns the %s (PHP %s()).\n", gm.name, gm.doc, t.Method)
		default:
			keys := localeKeys(t)
			fmt.Fprintf(&b, "// %s returns the %s for locale (PHP %s($locale)): %s; any other locale gets the default table.\n",
				gm.name, gm.doc, t.Method, strings.Join(quoteAll(keys), ", "))
		}
		fmt.Fprintf(&b, "func (e %s) %s(%s) string {\n", typ, gm.name, param)
		switch t.Kind {
		case kindIsValue:
			b.WriteString("\treturn string(e)\n}\n\n")
			continue
		case kindSingle:
			writeSwitch(&b, e, t.Tables[""], constName, "\t")
		case kindLocale:
			b.WriteString("\tswitch locale {\n")
			for _, k := range localeKeys(t) {
				fmt.Fprintf(&b, "\tcase %s:\n", strconv.Quote(k))
				writeSwitch(&b, e, t.Tables[k], constName, "\t\t")
				b.WriteString("\t\treturn \"\"\n")
			}
			b.WriteString("\t}\n")
			writeSwitch(&b, e, t.Tables[""], constName, "\t")
		}
		b.WriteString("\treturn \"\"\n}\n\n")
	}

	if e.GenOptions {
		fmt.Fprintf(&b, "// %sOptions returns {value, label} pairs for every case in PHP case order (the shape of PHP options($locale)).\n", typ)
		fmt.Fprintf(&b, "func %sOptions(locale string) []Option { return optionsOf(%s, locale) }\n", typ, casesVar)
	}

	code, err := format.Source([]byte(b.String()))
	if err != nil {
		return nil, fmt.Errorf("gofmt: %w\n%s", err, b.String())
	}
	return code, nil
}

func writeSwitch(b *strings.Builder, e *phpEnum, tbl map[string]string, constName func(phpCase) string, ind string) {
	fmt.Fprintf(b, "%sswitch e {\n", ind)
	for _, c := range e.Cases {
		fmt.Fprintf(b, "%scase %s:\n%s\treturn %s\n", ind, constName(c), ind, strconv.Quote(tbl[c.Name]))
	}
	fmt.Fprintf(b, "%s}\n", ind)
}

// localeKeys returns the explicit (non-default) locale keys, sorted.
func localeKeys(t phpTable) []string {
	var keys []string
	for k := range t.Tables {
		if k != "" {
			keys = append(keys, k)
		}
	}
	sort.Strings(keys)
	return keys
}

func quoteAll(ss []string) []string {
	out := make([]string, len(ss))
	for i, s := range ss {
		out[i] = strconv.Quote(s)
	}
	return out
}

// renderRegistry writes the test-only name → accessor table the PHP parity test walks, so a new PHP
// enum is covered without editing the test by hand.
func renderRegistry(enums []*phpEnum) ([]byte, error) {
	var b strings.Builder
	b.WriteString("// Code generated by enumgen. DO NOT EDIT.\n\npackage enums\n\n")
	b.WriteString("var generatedEnums = map[string]enumAccessor{\n")
	for _, e := range enums {
		typ := e.Name
		fmt.Fprintf(&b, "\t%s: {\n\t\tvalues: %sValues,\n", strconv.Quote(typ), typ)
		for _, t := range e.Methods {
			gm := goMethod[t.Method]
			if t.Method == "icon" {
				fmt.Fprintf(&b, "\t\ticon: func(v string) string { return %s(v).Icon() },\n", typ)
				continue
			}
			fmt.Fprintf(&b, "\t\t%s: func(v, locale string) string { return %s(v).%s(locale) },\n",
				t.Method, typ, gm.name)
		}
		if e.GenOptions {
			fmt.Fprintf(&b, "\t\toptions: %sOptions,\n", typ)
		}
		b.WriteString("\t},\n")
	}
	b.WriteString("}\n")
	code, err := format.Source([]byte(b.String()))
	if err != nil {
		return nil, fmt.Errorf("gofmt registry: %w", err)
	}
	return code, nil
}
