// Expected values are Carbon 3 / PHP 8.4 output:
//
//	date_default_timezone_set('Asia/Tehran');
//	Carbon::setTestNow(Carbon::parse('2026-09-23 14:05:06', 'Asia/Tehran'));
//	foreach ([...] as $s) {
//	    try { echo json_encode($s), ' => ', Carbon::parse($s)->format('Y-m-d H:i:s P'), "\n"; }
//	    catch (\Throwable $e) { echo json_encode($s), " => ERR\n"; }
//	}
//
// "2026-09-23" => 2026-09-23 00:00:00 +03:30      "2026-9-3" => 2026-09-03 00:00:00 +03:30
// "2026/09/23" => 2026-09-23 00:00:00 +03:30      "2026-02-30" => 2026-03-02 00:00:00 +03:30
// "2026-02-31" => 2026-03-03 00:00:00 +03:30      "2026-02-32" => ERR
// "2026-13-01" => ERR                             "2026-00-10" => 2025-12-10 00:00:00 +03:30
// "2026-01-00" => 2025-12-31 00:00:00 +03:30      "2026-09-23 10:20" => 2026-09-23 10:20:00 +03:30
// "2026-09-23T10:20:30" => 2026-09-23 10:20:30 +03:30
// "2026-09-23T10:20:30Z" => 2026-09-23 10:20:30 +00:00
// "2026-09-23T10:20:30+00:00" => 2026-09-23 10:20:30 +00:00
// "20260923" => 2026-09-23 00:00:00 +03:30        "today" => 2026-09-23 00:00:00 +03:30
// "tomorrow" => 2026-09-24 00:00:00 +03:30        "yesterday" => 2026-09-22 00:00:00 +03:30
// "now" => 2026-09-23 14:05:06 +03:30             "abc" => ERR
// "2026-09" => 2026-09-01 00:00:00 +03:30         "23-09-2026" => 2026-09-23 00:00:00 +03:30
// "09/23/2026" => 2026-09-23 00:00:00 +03:30      "" => 2026-09-23 14:05:06 +03:30
// "2026-09-23 25:00" => ERR                       " 2026-09-23 " => 2026-09-23 00:00:00 +03:30
// "2026-9-31" => 2026-10-01 00:00:00 +03:30
//
// Not supported on purpose (Carbon accepts them, no client sends them):
// "+1 day" => 2026-09-24 14:05:06 +03:30, "2026-09-23x" => 2026-09-23 00:00:00 -11:00 (military zone X),
// "2026-09-23T10:20:30+03:30abc" => 2026-09-23 10:20:30 +03:30 (trailing zone abbreviation).
//
// Extra shapes, same snippet with format('Y-m-d H:i:s.u P'):
// "2021-06-01" => 2021-06-01 00:00:00.000000 +04:30 (DST era)
// "2026-09-23 10:20:30.5" => 2026-09-23 10:20:30.500000 +03:30
// "2026-09-23T10:20:30-0130" => 2026-09-23 10:20:30.000000 -01:30
// "2026-09-23T10:20:30 +03:30" => 2026-09-23 10:20:30.000000 +03:30
// "2026-09-23 10:20:30.123456" => 2026-09-23 10:20:30.123456 +03:30
func TestParseLenient_MatchesCarbon(t *testing.T) {
	now := time.Date(2026, 9, 23, 14, 5, 6, 0, Tehran)
	const layout = "2006-01-02 15:04:05 -07:00"
	cases := map[string]string{
		"2026-09-23":                "2026-09-23 00:00:00 +03:30",
		"2026-9-3":                  "2026-09-03 00:00:00 +03:30",
		"2026/09/23":                "2026-09-23 00:00:00 +03:30",
		"2026-02-30":                "2026-03-02 00:00:00 +03:30",
		"2026-02-31":                "2026-03-03 00:00:00 +03:30",
		"2026-02-32":                "ERR",
		"2026-13-01":                "ERR",
		"2026-00-10":                "2025-12-10 00:00:00 +03:30",
		"2026-01-00":                "2025-12-31 00:00:00 +03:30",
		"2026-09-23 10:20":          "2026-09-23 10:20:00 +03:30",
		"2026-09-23T10:20:30":       "2026-09-23 10:20:30 +03:30",
		"2026-09-23T10:20:30Z":      "2026-09-23 10:20:30 +00:00",
		"2026-09-23T10:20:30+00:00": "2026-09-23 10:20:30 +00:00",
		"20260923":                  "2026-09-23 00:00:00 +03:30",
		"today":                     "2026-09-23 00:00:00 +03:30",
		"tomorrow":                  "2026-09-24 00:00:00 +03:30",
		"yesterday":                 "2026-09-22 00:00:00 +03:30",
		"now":                       "2026-09-23 14:05:06 +03:30",
		"abc":                       "ERR",
		"2026-09":                   "2026-09-01 00:00:00 +03:30",
		"23-09-2026":                "2026-09-23 00:00:00 +03:30",
		"09/23/2026":                "2026-09-23 00:00:00 +03:30",
		"":                          "2026-09-23 14:05:06 +03:30",
		"2026-09-23 25:00":          "ERR",
		" 2026-09-23 ":              "2026-09-23 00:00:00 +03:30",
		"2026-9-31":                 "2026-10-01 00:00:00 +03:30",
		// Extra shapes (transcript above).
		"2021-06-01":                   "2021-06-01 00:00:00 +04:30",
		"2026-09-23 10:20:30.5":        "2026-09-23 10:20:30 +03:30",
		"2026-09-23T10:20:30-0130":     "2026-09-23 10:20:30 -01:30",
		"2026-09-23T10:20:30 +03:30":   "2026-09-23 10:20:30 +03:30",
		"+1 day":                       "ERR",
		"2026-09-23x":                  "ERR",
		"2026-09-23T10:20:30+03:30abc": "ERR",
	}
	for in, want := range cases {
		got, err := ParseLenient(in, now, Tehran)
		if want == "ERR" {
			require.ErrorIs(t, err, ErrLenientFormat, "%q", in)
			continue
		}
		require.NoError(t, err, "%q", in)
		assert.Equal(t, want, got.Format(layout), "%q", in)
	}
}

func TestParseLenient_FractionAndNowZone(t *testing.T) {
	now := time.Date(2026, 9, 23, 10, 0, 0, 0, time.UTC) // 13:30 Tehran
	got, err := ParseLenient("2026-09-23 10:20:30.123456", now, Tehran)
	require.NoError(t, err)
	assert.Equal(t, 123456000, got.Nanosecond())
	got, err = ParseLenient("now", now, Tehran)
	require.NoError(t, err)
	assert.Equal(t, "2026-09-23 13:30:00 +03:30", got.Format("2006-01-02 15:04:05 -07:00"))
}
