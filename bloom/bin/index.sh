#!/usr/bin/env bash
# Regenerate bloom/INDEX.md from the task files.
set -euo pipefail
ROOT="$(cd "$(dirname "$0")/.." && pwd)"
field() { grep -m1 "^$2:" "$1" | sed -E "s/^$2: *//"; }
{
  echo "# Task index"; echo; echo "_Generated by \`bloom/bin/index.sh\` — do not edit by hand._"
  for ms in $(ls -d "$ROOT"/N*/ | xargs -n1 basename | sort -V); do
    echo; echo "## $ms"; echo; echo "| ID | Status | Group | Type | Depends on | Title |"; echo "|---|---|---|---|---|---|"
    for f in $(ls "$ROOT/$ms"/B-*.md | sort -t- -k3,3V); do
      echo "| [$(field "$f" id)]($ms/$(basename "$f")) | $(field "$f" status) | $(field "$f" parallel_group) | $(field "$f" type) | $(field "$f" depends_on | tr -d '[]') | $(field "$f" title) |"
    done
  done
} > "$ROOT/INDEX.md"
echo "wrote $ROOT/INDEX.md"
