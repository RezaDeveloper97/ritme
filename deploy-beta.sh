#!/usr/bin/env bash
# ─────────────────────────────────────────────────────────────────────────────
# Deploy Ritme BETA to https://beta.ritme.app.  Run from the repo root:
#     ./deploy-beta.sh
#
# A PUBLIC environment for REAL users. By default it ships your WORKING TREE
# (uncommitted edits included, like deploy.sh); `FROM_WORKTREE=0` ships the tip
# of a branch via `git archive` instead (like deploy-stage.sh). Same server as production
# and staging, fully separate otherwise:
#
#   source   /opt/ritme-beta           (stage: /opt/ritme-stage, prod: /opt/ritme)
#   project  ritme-beta                (own containers, network, volumes, DB)
#   URL      https://beta.ritme.app    (no password gate; ArvanCloud in front)
#   admin    https://beta-admin.ritme.app (admin-web at `/`, own host like adpanell)
#   APP_ENV  production                (fake adapters refused, debug off)
#
# First run on an empty server state does everything once, automatically:
#   - generates /opt/ritme-beta/.env (fresh secrets; SMS keys copied from
#     staging's .env) and /root/ritme-beta-credentials.txt (admin login)
#   - bootstraps the empty DB with Laravel BEFORE backend-go first starts
#     (schema, Passport keys + personal-access client, admin + content seeds;
#     docs/go-migration/cutover.md → "Stage runs Go only")
#   - mounts the beta vhost into production's proxy and gets a certificate
#
# Switches:
#   FROM_WORKTREE=0     ./deploy-beta.sh   ship the `stage` branch, not the disk
#   BRANCH=my-feature FROM_WORKTREE=0 ./deploy-beta.sh   ship another branch
#   SERVICES="frontend" ./deploy-beta.sh   only these services
#   NO_BUILD=1          ./deploy-beta.sh   restart without building
#   SKIP_SYNC=1         ./deploy-beta.sh   don't re-ship the source
# ─────────────────────────────────────────────────────────────────────────────
set -euo pipefail
cd "$(dirname "$0")"

SERVER="${SERVER:-root@89.251.8.115}"
SSH_KEY="${SSH_KEY:-$HOME/.ssh/id_ed25519}"
REMOTE_DIR="/opt/ritme-beta"
PROD_DIR="/opt/ritme"          # where the shared proxy and its config live
STAGE_DIR="/opt/ritme-stage"   # SMS keys are copied from here on first run
BETA_HOST="beta.ritme.app"
ADMIN_HOST="beta-admin.ritme.app"
BRANCH="${BRANCH:-stage}"      # only with FROM_WORKTREE=0
SERVICES="${SERVICES:-}"

SSH_OPTS=(-i "$SSH_KEY" -o ConnectTimeout=20 -o ServerAliveInterval=15 -o ServerAliveCountMax=8)
COMPOSE="docker compose -p ritme-beta -f docker-compose.yml -f docker-compose.beta.yml"
PROD_COMPOSE="docker compose -f docker-compose.yml -f docker-compose.prod.yml"

ssh_run() { ssh "${SSH_OPTS[@]}" "$SERVER" "$@"; }

# ── 1. Ship the source ──────────────────────────────────────────────────────
if [[ "${SKIP_SYNC:-0}" != "1" ]]; then
  if [[ "${FROM_WORKTREE:-1}" == "1" ]]; then
    SRC="./"
    echo "==> Syncing WORKING TREE ($(git rev-parse --short HEAD)$(git diff --quiet HEAD -- || echo '+dirty')) to ${SERVER}:${REMOTE_DIR} ..."
  else
    git rev-parse --verify "${BRANCH}^{commit}" >/dev/null 2>&1 \
      || { echo "!! branch '${BRANCH}' does not exist locally" >&2; exit 1; }
    SRC="$(mktemp -d)/"
    trap 'rm -rf "${SRC%/}"' EXIT
    git archive "$BRANCH" | tar -x -C "$SRC"
    echo "==> Syncing branch '${BRANCH}' ($(git rev-parse --short "$BRANCH")) to ${SERVER}:${REMOTE_DIR} ..."
  fi

  ssh_run "mkdir -p ${REMOTE_DIR}"
  rsync -az --delete --stats \
    --exclude '.git/' \
    --exclude 'node_modules/' \
    --exclude 'vendor/' \
    --exclude '.next/' \
    --exclude 'application/' \
    --exclude 'twa/' \
    --exclude 'android-shell/' \
    --exclude '*.tar.gz' \
    --exclude '*.fig' \
    --exclude '*.log' \
    --exclude '.env' \
    --exclude '.bootstrapped' \
    --exclude '.env.local' \
    --exclude 'ssl/' \
    --exclude 'certbot-www/' \
    --exclude 'backend/storage/*.key' \
    --exclude 'backend/storage/logs/*' \
    --exclude 'backend/storage/framework/cache/*' \
    --exclude 'backend/database/*.sqlite' \
    -e "ssh ${SSH_OPTS[*]}" \
    "$SRC" "${SERVER}:${REMOTE_DIR}/"
fi

# ── 2. Server-side .env (generated once, never overwritten) ─────────────────
ssh_run "docker network inspect ritme-edge >/dev/null 2>&1 || docker network create ritme-edge" >/dev/null
if ! ssh_run "test -f ${REMOTE_DIR}/.env"; then
  echo "==> Generating ${REMOTE_DIR}/.env (first deploy) ..."
  # Runs entirely on the server: secrets are generated there and never cross
  # this terminal. The admin login goes to a root-only file.
  ssh_run "REMOTE_DIR=${REMOTE_DIR} STAGE_DIR=${STAGE_DIR} BETA_HOST=${BETA_HOST} bash -s" <<'REMOTE'
set -euo pipefail
umask 077
r64() { openssl rand -base64 "$1" | tr -d '\n'; }
pw()  { openssl rand -hex 16; }
from_stage() { grep -E "^$1=" "${STAGE_DIR}/.env" 2>/dev/null | head -1 | cut -d= -f2- || true; }
admin_pw="$(pw)"
cat > "${REMOTE_DIR}/.env" <<ENV
# Ritme BETA (${BETA_HOST}) — generated by deploy-beta.sh. Server-only; see .env.beta.example.
APP_KEY=base64:$(r64 32)
APP_URL=https://${BETA_HOST}
DB_DATABASE=ritme_beta
DB_USERNAME=ritme_beta
DB_PASSWORD=$(pw)
DB_ROOT_PASSWORD=$(pw)
NEXT_PUBLIC_API_BASE_URL=https://${BETA_HOST}/api/v1
SITE_URL=https://${BETA_HOST}
ADMIN_SEED_EMAIL=admin@ritme.app
ADMIN_SEED_PASSWORD=${admin_pw}
SMS_PROVIDER=$(from_stage SMS_PROVIDER)
KAVENEGAR_API_KEY=$(from_stage KAVENEGAR_API_KEY)
KAVENEGAR_SENDER=$(from_stage KAVENEGAR_SENDER)
KAVENEGAR_TEMPLATE_LOGIN_OTP=$(from_stage KAVENEGAR_TEMPLATE_LOGIN_OTP)
SMSIR_API_KEY=$(from_stage SMSIR_API_KEY)
SMSIR_TEMPLATE_ID=$(from_stage SMSIR_TEMPLATE_ID)
SMSIR_LINE_NUMBER=$(from_stage SMSIR_LINE_NUMBER)
SWAGGER_USER=ritme
SWAGGER_PASSWORD=$(pw)
PAYMENT_PROVIDER=
ZARINPAL_MERCHANT_ID=
AI_PROVIDER=
GEMINI_API_KEY=
COMPANION_SMS_PROVIDER=
COMPANION_CODE_PEPPER=$(r64 48)
SHARE_CODE_PEPPER=$(r64 48)
PRIVATE_NOTE_KEY=$(r64 32)
LAB_FILE_KEY=$(r64 32)
FILE_KEY=$(r64 32)
MEDIA_URL_KEY=$(r64 32)
ENV
cat > /root/ritme-beta-credentials.txt <<CRED
Ritme BETA — https://${BETA_HOST}
Admin panel: https://beta-admin.ritme.app
  email:    admin@ritme.app
  password: ${admin_pw}
(all other secrets: ${REMOTE_DIR}/.env)
CRED
REMOTE
fi

# ── 3. Production proxy: beta vhost files, compose mount, placeholder cert ──
# deploy.sh ships the whole working tree to /opt/ritme, which this script must
# never do (it would swap production's source for the stage branch). So only
# the beta-owned nginx files are copied, and the mount lines are added to the
# server's docker-compose.prod.yml in place if they are not there yet — the
# repo's copy carries the same lines, so the next prod deploy keeps them.
echo "==> Installing the beta vhost into the production proxy ..."
rsync -az -e "ssh ${SSH_OPTS[*]}" \
  deploy/beta-ssl.conf deploy/beta-off.conf deploy/vhost-beta.inc deploy/vhost-beta-admin.inc deploy/enable-https-beta.sh \
  "${SERVER}:${PROD_DIR}/deploy/"
ssh_run "cd ${PROD_DIR} && grep -q 'zz-beta.conf' docker-compose.prod.yml || \
  sed -i 's#^\(\( *\)- \${SITE_CONF:-./deploy/site-off.conf}:/etc/nginx/conf.d/zz-site.conf:ro\)\$#\1\n\2- \${BETA_CONF:-./deploy/beta-off.conf}:/etc/nginx/conf.d/zz-beta.conf:ro\n\2- ./deploy/vhost-beta.inc:/etc/nginx/conf.d/vhost-beta.inc:ro#' docker-compose.prod.yml"
ssh_run "cd ${PROD_DIR} && grep -q 'vhost-beta-admin.inc' docker-compose.prod.yml || \
  sed -i 's#^\(\( *\)- ./deploy/vhost-beta.inc:/etc/nginx/conf.d/vhost-beta.inc:ro\)\$#\1\n\2- ./deploy/vhost-beta-admin.inc:/etc/nginx/conf.d/vhost-beta-admin.inc:ro#' docker-compose.prod.yml"
ssh_run "grep -q 'zz-beta.conf' ${PROD_DIR}/docker-compose.prod.yml && grep -q 'vhost-beta-admin.inc' ${PROD_DIR}/docker-compose.prod.yml" \
  || { echo "!! could not add the beta mounts to ${PROD_DIR}/docker-compose.prod.yml" >&2; exit 1; }
# Placeholder certificates (a copy of production's) so nginx can load the
# server blocks before enable-https-beta.sh has issued the real ones.
for p in beta beta-admin; do
  ssh_run "cd ${PROD_DIR} && test -s ssl/${p}-fullchain.pem || { cp ssl/fullchain.pem ssl/${p}-fullchain.pem && install -m 600 ssl/privkey.pem ssl/${p}-privkey.pem; }"
done

# ── 4. First deploy: bootstrap the empty DB with Laravel ────────────────────
# Must happen BEFORE backend-go ever starts on the volume: Go creates no
# Passport keys / oauth client and runs no seeders, and if goose builds the
# schema first, Laravel's migrations would collide with it later.
# Marker file, not the volume: a bootstrap that died halfway must run again.
if [[ "${NO_BUILD:-0}" != "1" ]] && ! ssh_run "test -f ${REMOTE_DIR}/.bootstrapped"; then
  if ssh_run "docker container inspect ritme-beta-backend-go-1 >/dev/null 2>&1"; then
    echo "!! backend-go already ran on this volume — a Laravel bootstrap now would collide with goose." >&2
    echo "   Wipe it (docker compose -p ritme-beta down -v) or touch ${REMOTE_DIR}/.bootstrapped." >&2
    exit 1
  fi
  echo "==> Fresh beta database — bootstrapping once with Laravel ..."
  ssh_run "REMOTE_DIR=${REMOTE_DIR} C='${COMPOSE}' bash -s" <<'REMOTE'
set -euo pipefail
cd "$REMOTE_DIR"
$C --profile laravel build backend
$C up -d --wait mysql redis
# The entrypoint migrates, creates the Passport keys + client and runs the base
# seeds (languages, admin, message contents, recommendations), then execs this:
# the content seeders it does not run itself.
$C --profile laravel run --rm --no-deps -T backend sh -c '
  for s in InfoSectionSeeder PhaseContentSeeder AffirmationSeeder TaskTemplateSeeder ArticleSeeder ChallengeSeeder PregnancyWeeklyContentSeeder; do
    php artisan db:seed --class="Database\\Seeders\\$s" --force || echo "!! seeder $s failed"
  done'
touch .bootstrapped
REMOTE
fi

# ── 5. Build and start (backend-go first: the frontend build reads its messages)
if [[ "${FROM_WORKTREE:-1}" == "1" ]]; then REV="$(git rev-parse --short HEAD)-wt"; else REV="$(git rev-parse --short "${BRANCH}")"; fi
BUILD_REV="${REV}-$(date -u +%Y%m%dT%H%M%SZ)"
wants() { [[ -z "$SERVICES" || " $SERVICES " == *" $1 "* ]]; }

# wait_ready — poll backend-go's GET /ready (MariaDB + Redis both answer, T-M9-10) until it is 200, from inside
# the container: the image has no shell or curl, so `api healthcheck ready` makes the request. /up (the Docker
# HEALTHCHECK) only says the process is alive. Gives up — and aborts the deploy — after ~60 s.
wait_ready() {
  echo "==> Waiting for backend-go /ready ..."
  ssh_run 'for i in $(seq 1 30); do
    if docker exec ritme-beta-backend-go-1 /app/api healthcheck ready >/dev/null 2>&1; then echo "  ready"; exit 0; fi
    sleep 2
  done
  echo "!! backend-go is not ready (GET /ready answers non-200: MariaDB or Redis unreachable)" >&2
  docker exec ritme-beta-backend-go-1 /app/api healthcheck ready >&2 || true
  exit 1'
}

if [[ "${NO_BUILD:-0}" != "1" ]]; then
  if wants backend-go; then
    echo "==> Building and starting backend-go first ..."
    ssh_run "cd ${REMOTE_DIR} && ${COMPOSE} build backend-go"
    ssh_run "cd ${REMOTE_DIR} && ${COMPOSE} up -d --wait --wait-timeout 180 backend-go"
    wait_ready
    ssh_run "docker logs ritme-beta-backend-go-1 2>&1 | grep '\"msg\":\"migrations\"' | tail -1" || true
  fi
  echo "==> Building beta images on the server (BUILD_REV=${BUILD_REV}) ..."
  ssh_run "cd ${REMOTE_DIR} && ${COMPOSE} build --build-arg BUILD_REV=${BUILD_REV} ${SERVICES}"
fi

echo "==> Starting beta stack ..."
ssh_run "cd ${REMOTE_DIR} && ${COMPOSE} up -d ${SERVICES}"
if wants backend-go; then wait_ready; fi
ssh_run "docker image prune -f" >/dev/null || true

# ── 6. Switch the vhost on (recreate: BETA_CONF selects a mount source) ─────
echo "==> Ensuring the proxy serves ${BETA_HOST} ..."
ssh_run "cd ${PROD_DIR} && { grep -q '^BETA_CONF=' .env || echo 'BETA_CONF=./deploy/beta-ssl.conf' >> .env; }"
ssh_run "cd ${PROD_DIR} && ${PROD_COMPOSE} up -d proxy && ${PROD_COMPOSE} exec -T proxy sh -c 'nginx -t && nginx -s reload'"

# Own certificate per host, once (keeps the placeholder if issuance fails).
for pair in "${BETA_HOST}:beta" "${ADMIN_HOST}:beta-admin"; do
  host="${pair%%:*}" prefix="${pair##*:}"
  if ! ssh_run "test -f /etc/letsencrypt/live/${host}/fullchain.pem"; then
    echo "==> Requesting a certificate for ${host} ..."
    ssh_run "cd ${PROD_DIR} && bash deploy/enable-https-beta.sh ${host} ${prefix}" || true
  fi
done

# ── 7. Verify ───────────────────────────────────────────────────────────────
echo "==> Verifying ..."
sleep 8
ssh_run "cd ${REMOTE_DIR} && ${COMPOSE} ps --format '{{.Service}}: {{.Status}}'"

failures=0
check() { # check <expected> <url> [extra curl args...]
  local expected="$1" url="$2"; shift 2
  local got
  got="$(curl -s -o /dev/null -m 25 -w '%{http_code}' "$@" "$url")" || got=000
  if [[ "$got" == "$expected" ]]; then
    printf '  ok    %s  %s\n' "$got" "$url"
  else
    printf '  FAIL  %s (expected %s)  %s\n' "$got" "$expected" "$url"
    failures=$((failures + 1))
  fi
}

BASE="https://${BETA_HOST}"
check 200 "${BASE}/up"
# Public: no password gate. 307 = next-intl's redirect to the default locale.
check 307 "${BASE}/"
check 200 "${BASE}/api/v1/languages" -H 'Accept: application/json'
# 401 from Go's auth middleware (not nginx): the API booted and is wired.
check 401 "${BASE}/api/v1/banners" -H 'Accept: application/json'
check 200 "${BASE}/manifest.webmanifest"
check 404 "${BASE}/oauth/token"
# The admin is NOT on the app host: its API 404s here, the old paths redirect.
check 404 "${BASE}/api/admin/v1/auth/me" -H 'Accept: application/json'
check 301 "${BASE}/admin"
check 301 "${BASE}/panel"

ADMIN="https://${ADMIN_HOST}"
check 200 "${ADMIN}/login"
# 401 from Go (JSON `unauthenticated`): ADMIN_HOSTS matches this host. A 404
# here means the admin API is disabled for it.
check 401 "${ADMIN}/api/admin/v1/auth/me" -H 'Accept: application/json'
check 200 "${ADMIN}/api/v1/languages" -H 'Accept: application/json'
check 404 "${ADMIN}/api/v1/banners" -H 'Accept: application/json'

if (( failures > 0 )); then
  echo "❌ Beta deploy finished but ${failures} check(s) failed — see above." >&2
  exit 1
fi
echo "✅ Beta deploy done — ${BASE} + ${ADMIN}  (admin login: ssh ${SERVER} cat /root/ritme-beta-credentials.txt)"
