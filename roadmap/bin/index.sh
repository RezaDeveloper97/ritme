#!/usr/bin/env bash
# Regenerate roadmap/INDEX.md from the task files.
set -euo pipefail
ROOT="$(cd "$(dirname "$0")/.." && pwd)"
field() { grep -m1 "^$2:" "$1" | sed -E "s/^$2: *//"; }
{
  echo "# Canvas-build index"; echo; echo "_Generated by \`roadmap/bin/index.sh\` — do not edit by hand._"
  for ep in $(ls -d "$ROOT"/E*/ | xargs -n1 basename | sort -V); do
    echo; echo "## $ep"; echo; echo "| ID | Status | Group | Type | Depends on | Boards | Title |"; echo "|---|---|---|---|---|---|---|"
    for f in $(ls "$ROOT/$ep"/CB-*.md | sort -V); do
      echo "| [$(field "$f" id)]($ep/$(basename "$f")) | $(field "$f" status) | $(field "$f" parallel_group) | $(field "$f" type) | $(field "$f" depends_on | tr -d '[]') | $(field "$f" boards | tr -d '[]' | sed 's/\.dc\.html//g') | $(field "$f" title) |"
    done
  done
} > "$ROOT/INDEX.md"
echo "wrote $ROOT/INDEX.md"
